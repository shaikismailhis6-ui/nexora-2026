// Generates src/data/roster.generated.ts from data-source/roster.csv
// Usage: npm run build:roster
// The roster is stored obfuscated (hashed key + XOR'd name) so the list is not
// readable as plain text in the bundle. It is NOT cryptographic security — the
// app is fully client-side — it just keeps the list from being casually browsed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const csv = readFileSync(resolve(here, '../data-source/roster.csv'), 'utf8').trim().split(/\r?\n/).slice(1)

const SALT = 'nexora-2k26'

function cyrb53(str, seed = 0) {
  let h1 = 0xdeadbeef ^ seed, h2 = 0x41c6ce57 ^ seed
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i)
    h1 = Math.imul(h1 ^ ch, 2654435761)
    h2 = Math.imul(h2 ^ ch, 1597334677)
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909)
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909)
  return 4294967296 * (2097151 & h2) + (h1 >>> 0)
}
function mulberry32(a) {
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
function encode(roll, name) {
  const rnd = mulberry32(cyrb53(roll + SALT) >>> 0)
  let out = ''
  for (let i = 0; i < name.length; i++) out += String.fromCharCode(name.charCodeAt(i) ^ Math.floor(rnd() * 256))
  return Buffer.from(out, 'latin1').toString('base64')
}

const entries = {}
for (const line of csv) {
  const idx = line.indexOf(',')
  const roll = line.slice(0, idx).trim().toUpperCase()
  const name = line.slice(idx + 1).trim().replace(/^"|"$/g, '').replace(/\s+/g, ' ').toUpperCase()
  if (!/^[0-9A-Z]{10}$/.test(roll)) throw new Error('Bad roll: ' + roll)
  const key = cyrb53(roll, 7).toString(36)
  if (entries[key]) throw new Error('Hash collision for ' + roll)
  entries[key] = encode(roll, name)
}

const outDir = resolve(here, '../src/data')
mkdirSync(outDir, { recursive: true })
writeFileSync(
  resolve(outDir, 'roster.generated.ts'),
  `// AUTO-GENERATED by scripts/build-roster.mjs — do not edit by hand.\nexport const ROSTER_SALT = ${JSON.stringify(SALT)}\nexport const ROSTER: Record<string, string> = ${JSON.stringify(entries)}\n`
)
console.log(`Roster generated: ${Object.keys(entries).length} students`)
